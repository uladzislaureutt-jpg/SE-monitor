"""Guarded-recall regressions from the independent audit of production run 39.

The positive corpus represents every definite miss and every editorially
accepted borderline class from the audit.  The negative corpus locks the
precision boundary: update76 must not lower the global score or turn generic
politics, crime, market statistics, advice and neutral service news into
report cards.
"""

from pathlib import Path

import pytest

import social_monitor as sm


SETTINGS = sm.load_settings(
    Path(__file__).resolve().parents[1] / "config" / "settings.yaml"
)


def source(locality: str = "Беларусь") -> sm.Source:
    return sm.Source(
        enabled=True,
        country="Беларусь",
        country_code="BY",
        locality=locality,
        rank=1,
        priority="A",
        name="Тестовый источник",
        media_type="website",
        domain="example.by",
        start_url="https://example.by",
        language="ru",
        adapter="standard",
    )


def decision(title: str, text: str, locality: str = "Беларусь"):
    return sm.evaluate_relevance(title, "", text, source(locality), SETTINGS)


