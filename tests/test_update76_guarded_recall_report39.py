def test_authority_exception_requires_a_bound_unresolved_social_failure():
    political = decision(
        "Лукашенко выступил на совещании по вопросам дорог",
        "Президент поручил правительству обсудить финансирование отрасли.",
    )
    appeal = decision(
        "Житель обратился к Лукашенко из-за разрушенной дороги",
        "Дорогу не ремонтируют несколько лет, прежние обращения не помогли.",
    )
    assert not political.relevant
    assert appeal.relevant
    assert appeal.category == "Дороги и благоустройство"


def test_crime_exception_requires_collective_consumer_scale():
    single_case = decision(
        "Один покупатель не получил шкаф и обратился в РУВД",
        "Клиент заплатил продавцу, но заказ не получил. Милиция начала проверку.",
    )
    mass_case = decision(
        "Клиенты мебельной фирмы остались без заказов",
        "Более 200 пострадавших заплатили за кухни, но мебель не получили. "
        "Заявления направлены в РУВД.",
    )
    assert not single_case.relevant
    assert mass_case.relevant
    assert mass_case.category == "Качество товаров и услуг"
