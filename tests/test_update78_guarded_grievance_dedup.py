def article(
    title: str,
    excerpt: str,
    source_name: str,
    url: str,
    *,
    region: str = "",
) -> sm.ArticleResult:
    return sm.ArticleResult(
        source_name=source_name,
        source_type="website",
        country="Беларусь",
        locality="Беларусь",
        priority="A",
        source_language="ru",
        title=title,
        title_generated=False,
        url=url,
        published_at="2026-09-03T12:00:00+00:00",
        category="Законы, права и общественное регулирование",
        subcategory="",
        excerpt=excerpt,
        signal_type="общественная реакция",
        official_response=False,
        score=10,
        matched_terms="",
        discovered_via="homepage",
        text_length=len(excerpt),
        event_region=region,
    )


@pytest.mark.parametrize(
    ("left", "right"),
    (
        (
            article("В Могилеве завышали цены на питьевую воду", "Производитель бутилированной воды завышал отпускные цены.", "Источник А", "https://a.by/water"),
            article("Цены на бутилированную воду оказались завышены", "В Могилеве питьевую воду продавали по ценам, не подтвержденным экономическими расчетами.", "Источник Б", "https://b.by/water"),
        ),
        (
            article("Изменились правила электронной очереди на границе", "Опубликован новый порядок регистрации электронной очереди на границе.", "Источник А", "https://a.by/queue"),
            article("Новый порядок пересечения границы", "Правила электронной очереди на границе вступили в силу.", "Источник Б", "https://b.by/queue"),
        ),
        (
            article("Гранитная лавочка в Бресте вызвала черный юмор", "Объект напоминает надгробие.", "NewGrodno", "https://a.by/bench", region="Могилевская область"),
            article("Брестчане обсуждают место для вечного отдыха", "Жуткая лавочка похожа на кладбищенский памятник.", "BGmedia", "https://b.by/bench", region="Брестская область"),
        ),
        (
            article("На озере Дальва почти исчезла вода", "Уровень воды в озере Дальва резко снизился.", "Белсат", "https://a.by/dalva"),
            article("Озеро Дальва обмелело", "Жители увидели низкий уровень воды: водоем пересох.", "BGmedia", "https://b.by/dalva"),
        ),
    ),
)
def test_run41_rewrites_form_one_card(left: sm.ArticleResult, right: sm.ArticleResult) -> None:
    consolidated = sm.deduplicate_results([left, right])
    assert len(consolidated) == 1
    assert sm.represented_publication_count(consolidated) == 2


def test_source_name_variants_do_not_create_fake_related_coverage() -> None:
    left = article("На озере Дальва почти исчезла вода", "Озеро Дальва обмелело.", "Издание Online", "https://a.by/dalva")
    right = article("Озеро Дальва обмелело", "На озере Дальва низкий уровень воды.", "Издание Онлайн", "https://b.by/dalva")
    consolidated = sm.deduplicate_results([left, right])
    assert len(consolidated) == 1
    assert consolidated[0].related_coverage == ()


